// Experiments that need no model invocation: discovery (POC-01), isolated session lifecycle with a scoped MCP tool (POC-02),
// and single-writer enforcement (POC-05). Every turn-related probe lives in experiments-turns.mjs.
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { performance } from 'node:perf_hooks';
import { AppServer, CODEX_EXE } from './codex-app-server.mjs';
import { check, verdict, home, listNames, sha256File, ECHO_MCP, WORKSPACE, RUN_ROOT, ensureDirs, writeResult } from './poc-common.mjs';

export const SECONDARY_CODEX_EXE = 'C:/Users/jusse/AppData/Local/OpenAI/Codex/bin/codex.exe';
export const DEFAULT_CODEX_HOME = 'C:/Users/jusse/.codex';
const DEVELOPER_MARKER = (tag) => `DESZO_ADR7_POC_${tag}_${Math.random().toString(36).slice(2, 10)}`;

export function runCli(exe, args, env = {}) {
  const started = performance.now();
  const result = spawnSync(exe, args, { encoding: 'utf8', windowsHide: true, timeout: 120000, env: { ...process.env, ...env } });
  return { status: result.status, signal: result.signal, stdout: (result.stdout || '').trim(), stderr: (result.stderr || '').trim().slice(0, 1500), durationMs: Math.round(performance.now() - started) };
}

const developerItem = text => ({ type: 'message', role: 'developer', content: [{ type: 'input_text', text }] });

export async function poc01() {
  ensureDirs();
  const checks = [], trace = [];
  const versions = {};
  for (const [label, exe] of [['active-desktop-runtime', CODEX_EXE], ['secondary-bin-launcher', SECONDARY_CODEX_EXE]]) {
    const version = runCli(exe, ['--version']);
    versions[label] = { exe: exe.split('/').slice(-2).join('/'), sha256: sha256File(exe), version: version.stdout };
  }
  checks.push(check('active runtime reports 0.163.0-alpha.10.2', versions['active-desktop-runtime'].version.includes('0.163.0-alpha.10.2'), versions['active-desktop-runtime'].version));
  checks.push(check('secondary launcher reports 0.130.0-alpha.5', versions['secondary-bin-launcher'].version.includes('0.130.0-alpha.5'), versions['secondary-bin-launcher'].version));

  const schemaDir = `${RUN_ROOT}/schema-0.163`;
  const schema = runCli(CODEX_EXE, ['app-server', 'generate-json-schema', '--experimental', '--out', schemaDir]);
  checks.push(check('protocol schema generated by the installed binary', schema.status === 0, schema.stderr || null));
  const methodsFound = new Set();
  for (const file of ['ClientRequest.json', 'ServerNotification.json', 'ClientNotification.json']) {
    const text = existsSync(join(schemaDir, file)) ? readFileSync(join(schemaDir, file), 'utf8') : '';
    for (const name of ['thread/start', 'thread/resume', 'thread/inject_items', 'turn/start', 'turn/steer', 'turn/interrupt', 'thread/queue/add', 'thread/queue/list', 'turn/started', 'turn/completed', 'thread/status/changed', 'thread/unsubscribe', 'mcpServerStatus/list']) {
      if (text.includes(`"${name}"`)) methodsFound.add(name);
    }
  }
  const needed = ['thread/start', 'thread/resume', 'turn/start', 'turn/steer', 'turn/interrupt', 'thread/queue/add', 'turn/started', 'turn/completed', 'thread/status/changed'];
  checks.push(check('documented methods needed by the design exist in the installed schema', needed.every(name => methodsFound.has(name)), [...methodsFound].sort().join(', ')));

  const login = runCli(CODEX_EXE, ['login', 'status'], { CODEX_HOME: home('poc01-isolated-login') });
  const loginText = `${login.stdout}\n${login.stderr}`;
  checks.push(check('a fresh isolated CODEX_HOME starts unauthenticated (no credential copied)', /Not logged in/i.test(loginText), loginText.trim().slice(-160)));
  const defaultLogin = runCli(CODEX_EXE, ['login', 'status']);
  trace.push({ item: 'default-profile login state (method only)', output: defaultLogin.stdout.includes('ChatGPT') ? 'logged in using ChatGPT' : defaultLogin.stdout.slice(0, 80) });

  const help = runCli(CODEX_EXE, ['app-server', '--help']);
  const transports = ['stdio://', 'unix://', 'ws://IP:PORT'].filter(item => help.stdout.includes(item));
  checks.push(check('app-server offers stdio, unix and ws transports', transports.length === 3, transports.join(', ')));

  const verdictValue = verdict(checks, { inconclusive: null });
  const record = {
    experiment: 'POC-01', title: 'Environment and capability discovery', status: verdictValue, checks,
    versions, schemaGeneration: { exitCode: schema.status, durationMs: schema.durationMs, outDir: schemaDir },
    notes: [
      'Two codex binaries are installed. The desktop app runs the 0.163.0-alpha.10.2 binary from the versioned folder; the bin/codex.exe launcher is 0.130.0-alpha.5. Only the former is the tested target.',
      'Documented capability (schema): thread/start, thread/resume, thread/inject_items, turn/start, turn/steer (expectedTurnId), turn/interrupt, thread/queue/*, turn/started, turn/completed, thread/status/changed.',
      'Observed behaviour is recorded by POC-02 to POC-08; schema presence alone does not establish that a method behaves as described.',
    ],
    trace,
  };
  writeResult('POC-01', record);
  return record;
}

export async function poc02() {
  ensureDirs();
  const checks = [], trace = [], measurements = {};
  const isolated = home('poc02-isolated');
  const a = new AppServer({ name: 'A', codexHome: isolated });
  const initA = await a.start();
  measurements.reportedCodexHomeMatchesRequest = initA.result?.codexHome;
  checks.push(check('the app-server reports the requested isolated CODEX_HOME', String(initA.result?.codexHome).replaceAll('\\', '/').endsWith('home-poc02-isolated'), initA.result?.codexHome));

  const started = await a.call('thread/start', { cwd: WORKSPACE });
  checks.push(check('a dedicated session is created in the isolated home', started.ok, started.error?.message));
  const thread = started.result?.thread;
  const threadId = thread?.id, rolloutPath = thread?.path;
  trace.push({ step: 'thread/start', threadId, status: thread?.status, durationMs: started.durationMs });
  checks.push(check('the session is recorded under the isolated home', Boolean(rolloutPath) && rolloutPath.replaceAll('\\', '/').includes('/home-poc02-isolated/'), rolloutPath));
  measurements.rolloutFileExistsAtCreation = Boolean(rolloutPath) && existsSync(rolloutPath);

  const marker = DEVELOPER_MARKER('CTX');
  const inject = await a.call('thread/inject_items', { threadId, items: [developerItem(`Context marker ${marker}`)] });
  checks.push(check('context can be written to the session without a model invocation', inject.ok, inject.error?.message));
  const onDiskBefore = existsSync(rolloutPath) && readFileSync(rolloutPath, 'utf8').includes(marker);
  checks.push(check('the injected context is persisted in the rollout file', onDiskBefore));

  const readA = await a.call('thread/read', { threadId, includeTurns: false });
  checks.push(check('the session status is readable by its controlling process', readA.ok && readA.result?.thread?.status?.type, readA.result?.thread?.status?.type));
  await a.kill('simulate controlling-process exit');
  trace.push({ step: 'process A exited', exit: a.exit });

  const b = new AppServer({ name: 'B', codexHome: isolated });
  await b.start();
  const resumed = await b.call('thread/resume', { threadId });
  checks.push(check('a new process resumes the same session identity after the controlling process exits', resumed.ok && resumed.result?.thread?.id === threadId, resumed.error?.message));
  // The server may return the Windows extended-length form (\\?\...) for the same file. Strip that prefix before comparing.
  const normalize = value => String(value ?? '').replace(/^\\\\\?\\/, '').replace(/^\/\/\?\//, '').replaceAll('\\', '/').toLowerCase();
  measurements.rolloutPathAtStart = rolloutPath;
  measurements.rolloutPathAtResume = resumed.result?.thread?.path ?? resumed.error?.message;
  checks.push(check('the resumed session still refers to the same rollout file', normalize(resumed.result?.thread?.path) === normalize(rolloutPath), null));
  checks.push(check('the persisted context survives the restart on disk', readFileSync(rolloutPath, 'utf8').includes(marker)));
  measurements.resumeDurationMs = resumed.durationMs;
  await b.kill('simulate worker restart');

  // Scoped MCP tool: a harmless read-only server registered in the isolated home only.
  const add = runCli(CODEX_EXE, ['mcp', 'add', 'poc-echo', '--', process.execPath.replaceAll('\\', '/'), ECHO_MCP], { CODEX_HOME: isolated });
  checks.push(check('a scoped MCP server is registered in the isolated home', add.status === 0, add.stderr || add.stdout || null));

  const c = new AppServer({ name: 'C', codexHome: isolated });
  await c.start();
  const status = await c.call('mcpServerStatus/list', { detail: 'full' });
  const serialized = JSON.stringify(status.result ?? status.error ?? {});
  checks.push(check('the registered MCP server is loaded in the isolated session', serialized.includes('poc-echo'), serialized.slice(0, 200)));
  checks.push(check('the scoped tool is listed for the resumed session', serialized.includes('poc_scoped_echo'), null));
  const resumedWithTools = await c.call('thread/resume', { threadId });
  checks.push(check('the session resumes with its scoped tools still registered', resumedWithTools.ok, resumedWithTools.error?.message));
  await c.kill('end of isolated-session test');

  // Ordinary user-profile exposure: a second, separate home stands in for another client profile. It is never the default profile.
  const otherProfile = home('poc02-other-client-profile');
  const d = new AppServer({ name: 'D', codexHome: otherProfile });
  await d.start();
  const listed = await d.call('thread/list', { limit: 50 });
  const listedIds = (listed.result?.data || []).map(item => item.id);
  checks.push(check('the other client profile does not list the dedicated session', !listedIds.includes(threadId), `listed=${listedIds.length}`));
  const byId = await d.call('thread/resume', { threadId });
  checks.push(check('the other client profile cannot resume the dedicated session by its identifier', !byId.ok, byId.ok ? 'resumed by id' : byId.error?.message));
  await d.kill('end of other-profile test');

  const record = {
    experiment: 'POC-02', title: 'Isolated dedicated session', status: verdict(checks), checks, measurements,
    ids: { threadId }, trace,
    notes: ['Resume by identifier across homes is refused. Path-based resume is tested separately in POC-05 and is not covered by this result.'],
  };
  writeResult('POC-02', record);
  return record;
}

